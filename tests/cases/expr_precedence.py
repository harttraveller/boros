# Operator precedence and associativity.
print(-2 ** 2, (-2) ** 2, 2 ** -1, -2 ** -2)
print(2 ** 3 ** 2, (2 ** 3) ** 2)
print(-3 ** 2 * 2, 2 * -3 ** 2)
print(~1 ** 2, ~-1, -~1, --1, +-+1, not -1)
print(2 ** -~1, 10 - 2 - 3, 100 / 10 / 5, 100 // 7 // 2, 2 ** 2 ** -1)
print(7 % 4 % 3, 2 * 3 % 4, 2 + 3 * 4 ** 2 // 5 % 7 - 1)
print(1 + 2 << 3, 1 << 2 + 3, 64 >> 2 >> 1, 1 << 3 >> 1)
print(6 & 3 | 8, 6 | 3 & 8, 6 ^ 3 & 1, 6 & 3 ^ 1, 1 | 2 ^ 3 & 4)
print(5 & 3 == 1, (5 & 3) == 1, 1 < 2 == 2, 3 | 4 < 8)
print(not 1 == 2, not 1 and 0, not (1 and 0), 1 or 0 and 0, (1 or 0) and 0)
print(1 if 0 else 2 if 0 else 3, (1 if 0 else 2) if 1 else 3)
print(-1 if not 0 else 1)
f = lambda x: x + 1 if x else -1
print(f(0), f(5))
print(2 * 3 ** 2, (2 * 3) ** 2, -(2 ** 2), (-2) ** 3, -2 ** 3)
print(2 ** -2 ** 2, 4 ** 0.5, (-8) ** (1 / 3) == (-8) ** (1 / 3))
print(10 - -3, 10 + -3, 10 - +3, 10 * -1 ** 2)
print(3 - 2 - 1, 3 - (2 - 1), 2 ** 2 ** 0, 8 / 2 * 4, 8 / (2 * 4))
print(1 + 2 * 3 - 4 / 2, 17 // 5 * 5 + 17 % 5)
print(-7 // 2 * 2, -(7 // 2) * 2, -7 % 3)
print([1, 2][0] ** 2, (lambda: 3)() ** 2, "ab" * 2 + "c", "x" + "y" * 3)
print(1 in [1] == True, (1 in [1]) == True, 2 not in [1] is True)
print(not 0 in [0], (not 0) in [0, True])
x = 5
print(x == 5 or x / 0, x != 5 and x / 0)
print(0 or [] or {} or "last", 1 and 2 and 3, 1 and 0 and 3)
print(~0, ~5, ~-6, -~-~0)
print(True + True, True * 3, -True, ~True, True << 3)
print(1 - 2 ** 3 ** 0, (1, 2) + (3,) * 2)
print(2 ** 10 >> 3 & 0xF, 0b1010 ^ 0o17 | 0x3)
print(3 > 2 > 1, 3 > 2 < 1, 1 < 2 < 3 < 4 > 0)
print(divmod(-7, 2), -7 // 2, -7 % 2, 7 // -2, 7 % -2)
